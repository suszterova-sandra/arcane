  MEDIA_CONSULTANT VARCHAR(160) NOT NULL,
  DATA_CONSULTANT VARCHAR(160) NOT NULL,
  MONTHLY_BUDGET_EUR NUMERIC(14,2) NOT NULL,
  WDF__CLIENT_ID VARCHAR(64) NOT NULL
